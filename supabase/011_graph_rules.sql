-- Цепочки реакций: «предъявил улику X этому персонажу → (если собраны
-- requires) → реплика + выдача улик grants». Формат:
-- [{ "id": "R12", "on": "<evidence_id>", "requires": ["<evidence_id>", ...],
--    "text": "реплика", "grants": ["<evidence_id>", ...], "group": "valentina-confession" }]
-- group — взаимоисключающие варианты одной сцены: если выдаваемое правилом уже
-- собрано другим вариантом группы, показывается короткий повтор, а не сцена целиком.
alter table characters
  add column if not exists reaction_rules jsonb not null default '[]'::jsonb;

-- Персонаж появляется на доске только после того, как собрана ЛЮБАЯ из этих
-- улик (плюс обычное условие — игрок побывал в его локации). null/пусто = без условия.
alter table characters
  add column if not exists unlock_evidence_ids uuid[];

-- Локация открывается, когда собрана ЛЮБАЯ из этих улик. null/пусто = без условия.
alter table locations
  add column if not exists unlock_evidence_ids uuid[];

-- Улика доступна (в обыске или автоматически), только если выполнен хотя бы
-- один набор: [["a","b"],["a","c"]] = (a и b) или (a и c). null = без условия.
alter table evidence
  add column if not exists requires_any jsonb;

-- true = улика выдаётся автоматически, как только выполнен requires_any
-- (например, санкция прокурора на задержание), без обыска и без реакции.
alter table evidence
  add column if not exists auto_grant boolean not null default false;
