-- is_suspect уже различает "подозреваемый" / "свидетель", но не отличает
-- реального фигуранта дела от персонажа вводной сцены — оба варианта
-- встречаются с is_suspect = false (например, мать пропавшего — реальный
-- свидетель с is_suspect=false, а дежурный ГУВД — тоже is_suspect=false).
-- Отдельный флаг, default true, чтобы все существующие строки не потеряли
-- статус, кроме явно проставленных исключений ниже.
alter table characters
  add column if not exists is_case_subject boolean not null default true;

update characters
  set is_case_subject = false
  where name = 'Азамат Нурланович';
