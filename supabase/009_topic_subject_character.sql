-- ============================================================
-- Дело №9704: фикс — персонаж видел тему про самого себя в своём же
-- "Спросить про..." (например, Виктор Гринько видел тему "Виктор
-- Гринько"). У topics не было явной связи "эта тема — про какого
-- персонажа", единственным ориентиром было совпадение topics.label с
-- characters.name — ненадёжно и не универсально (у "Марата",
-- "Тёти Розы", "Фархада Мамаджанова" label не совпадает буквально с
-- name персонажа: кавычки/приставки в имени карточки).
-- Добавляем явную FK-связь темы с её субъектом — код фильтрует по id,
-- не по строке.
-- Выполните этот файл в Supabase SQL Editor.
-- ============================================================

alter table topics
  add column if not exists subject_character_id uuid references characters(id);
